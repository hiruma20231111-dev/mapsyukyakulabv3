// 診断モードのユーザープロンプト生成。v1 api/ai/route.js の uq 構築を一字一句移植。
// @@FIX:key@@ / @@RIVAL:<本文>@@ の規約を保持。
import { LEVERS } from "@/content/levers";

export interface DiagnoseAnswer {
  q: string;
  label: string;
}
export interface DiagnosisSummary {
  total: number;
  grade: string;
  levers: Record<string, number | null>;
  answers: DiagnoseAnswer[];
}
export interface WeakItemRef {
  k: string;
  q: string;
}
export interface SimLiftInfo {
  lever: string;
  gain: number;
  items: string[];
}
export interface SimInfo {
  bizLabel?: string;
  sel: number;
  visits: number;
  ceiling: number;
  lifts: SimLiftInfo[];
}
export interface DiagnosePromptInput {
  diagnosis: DiagnosisSummary;
  weakItems?: WeakItemRef[];
  background?: string;
  bizLabel?: string;
  simInfo?: SimInfo;
}

export function buildDiagnoseUserPrompt(input: DiagnosePromptInput): string {
  const { diagnosis, weakItems, background, bizLabel, simInfo } = input;
  const ansText = (diagnosis.answers || []).map((a) => `・${a.q} → ${a.label}`).join("\n");
  const q = (v: number | null) => (v != null && v >= 72 ? "強い" : v != null && v >= 48 ? "ふつう" : "弱い(伸びしろ)");
  const lev = Object.entries(diagnosis.levers || {})
    .map(([k, v]) => `${LEVERS.find((x) => x.k === k)?.nm || k}:${q(v)}`)
    .join(" / ");
  const weakList =
    Array.isArray(weakItems) && weakItems.length ? weakItems.map((w) => `- key=${w.k} ｜ ${w.q}`).join("\n") : "";

  let uq = `以下は、あるお店のGoogleマップ活用の「簡易セルフ診断」の回答です。あなたは診断・評価の担当です。GBP完全ガイド(知識パック)の優先順に照らして「今の状態を評価」し、「何が足りていて/足りないか」と「直すとどう良くなるか(一般的傾向)」を言語化してください。\n\n【集客の4つの力の傾向】${lev}\n\n【設問への回答(本人)】\n${ansText}`;
  if (background) uq += `\n\n【収集情報(AIがGBP/Web検索で取得した5項目・参考値)】\n${background}`;
  if (simInfo) {
    const liftTxt = (simInfo.lifts || []).map((l) => `${l.lever}(${(l.items || []).join("・")})→+${l.gain}人`).join(" / ");
    uq += `\n\n【1000人シミュレーション（データベースの予測・参考）】画面には次が表示済み：「${simInfo.bizLabel || ""}で近くを探す1000人のうち、いまは約${simInfo.sel}人が"選択"、そのうち約${simInfo.visits}人が"来店"につながりそう」／直すと増える内訳：${liftTxt}／ぜんぶ整えば最大 約${simInfo.ceiling}人。\n必ず新セクション「## 🎯 来店見込みシミュレーションの評価」を作り、この「1000人→選択${simInfo.sel}人→来店${simInfo.visits}人」というファネルを2〜4文で評価する：①選択の多寡（同業の中で強い/弱い）②選ばれても“来店の入口=予約導線/行動”で取りこぼしていないか（選択と来店の差）③どこを直すと選択・来店が伸びるか。数字は上記の値をそのまま使い、勝手に別の数字を作らない。`;
  }
  if (weakList) uq += `\n\n【対象項目】『足りていないこと』では“この項目だけ”を、この順で1つずつブロックにし、各ブロックの「直すとどう良くなるか」の直後に @@FIX:key@@ を必ず出力する（keyは下記のものを厳密に使用）:\n${weakList}`;
  uq += `\n\n【最優先・データの扱い】この診断は「収集情報(GBPから取得した5項目)」と「設問への回答」の両方を確認して行う。設問への回答が唯一の正（ユーザー本人の申告）で、収集情報は補足の“参考値”。両者が矛盾する場合は必ず設問回答を採用し、設問と食い違う事実を断定しない（触れるなら「検索では〜でしたが、ご回答を優先します」と軽く）。収集情報が「不明」の項目は無理に断定せず、設問回答と一般論で評価する。数値は捏造しない。\n\n【この画面の役割＝“診断と評価”】\n- ここは『現状の評価』フェーズ。今できていること／足りないこと、そして各項目を『直すとどう良くなるか(一般的傾向)』までを述べる。\n- 「良くなる」の軸はGBP完全ガイドに沿って、まず“Googleからの評価が上がり→Googleマップ/ローカル検索の表示順位が上がりやすくなる”ことを中心に伝える（そのうえでAI検索にも選ばれやすくなる、と続ける）。AIの話だけに偏らない。\n- 【重要】具体的な「今日やる手順」「最初の3手」などの“行動プラン”はここでは書かない。それは次の「AIに相談」で一緒に決める。最後にその旨を案内する。\n- 評価はGBP完全ガイドの優先順(①基本情報・カテゴリ・属性→②クチコミ本文と返信→③写真・投稿の鮮度→④外部サイト掲載/NAP一貫→⑤AI検索での見え方)に従う。\n\n【出力ルール】\n- 点数・スコア（◯点/A〜D）は書かない。評価は「なぜそう言えるか」の根拠つきで。\n- 各セクションは必ず Markdown見出し「## 」で始める。簡潔に、箇条書きは「- 」で。\n- 専門用語は使わない（DIAG_RULESの言葉づかいルールを厳守）。「レバー」という語は絶対に出力しない。\n${background ? "- 【重要】収集情報(検索で取れた項目=業種・クチコミ点数・クチコミ数・エリア)がある場合は、総評の冒頭でその具体的な値に必ず一度言及し、設問回答と突き合わせて評価する。ただし『検索による参考値』である旨を添え、『不明』の項目は断定しない(存在を勝手に決めつけない)。\n" : ""}\n【セクション構成】\n## 🩺 総評\n(現在地。GBPガイドに照らして、土台と運用の状態を一言。良い点と一番の課題を根拠つきで。予備知識があればここで具体値に言及)\n## ✅ できていること\n(設問・背景から、今できている点を根拠つきで具体的に。ちゃんと褒める)\n## 📌 足りていないこと（直すとどうなるか）\n(GBP完全ガイドの優先順で、今足りない点を挙げる。${weakList ? "下記【対象項目】の" + (Array.isArray(weakItems) ? weakItems.length : 0) + "項目を、リストの順で1項目ずつブロックにする（勝手に項目を足さない/減らさない）。" : ""}各項目は必ず次の3行構成：1行目に太字で「その項目の見出し（例：**クチコミへの返信が少ない**）」、次に「**対策の方向性**：…」、次に「**直すとどう良くなるか**：…」。良くなる点は次の順で述べる：①まずGoogleからの評価(関連性・距離・知名度＝お店との合致度・近さ・知られている度合い)が上がり、Googleマップ/ローカル検索での表示順位が上がりやすくなる ②その結果お客さんに見つかる・選ばれる・来店につながりやすい ③さらにAI検索(AIのおすすめ)にも選ばれやすくなる。いずれも“一般的な傾向で保証はしない”と分かる言い方で、専門語は平易に。※“今日やる手順”までは踏み込まない。\n【最重要・印の出力】各項目の「直すとどう良くなるか」の文の“直後”に、その項目の識別印を必ず半角で 1回だけ出力する。形式は @@FIX:キー@@（キーは下記【対象項目】の key をそのまま使う）。例：…一般的な傾向があるで。@@FIX:reply@@ ／ この印はアプリが『興味ある？』ボタンに置き換えるので画面には出ない。印は各項目にちょうど1つ、絶対に省略しない。キーはリストのものだけを使い、勝手に作らない)\n## 🤖 AI検索（AIのおすすめ）での見え方\n(今の情報の具体性・一貫性から、ChatGPT/Gemini等のAIやGoogleのAI要約・おすすめに『選ばれやすい状態か・何が足りないか』を評価。AIに聞くタイプの検索は「順位でなく選ばれるか外れるか」である点も平易に。この段落の最後に、別行で @@FIX:aio@@ を必ず1回だけ出力する。この印はアプリが『興味ある？』ボタンに置き換えるので画面には出ない)\n## 🔗 外部サイトでの掲載（実在の裏づけ）\n(HP・SNS・食べログ等での店名/住所/電話の掲載・一貫の状況を評価。足りなければ、知られている度合いとAIの確信にどう効くかを一般的傾向で。※クチコミの集め方には触れない。ただし『有料だから』等の断り書きも書かない。この段落の最後に、別行で @@FIX:citation@@ を必ず1回だけ出力する。この印はアプリが『興味ある？』ボタンに置き換えるので画面には出ない)\n## ⚠️ 注意\n(規約リスク・効果は一般的傾向で保証しない旨)\n## 💬 次のステップ\n(「具体的な“今日やること”や“最初の3手”は、下の『AIに相談』で、あなたのお店に合わせて一緒に決めましょう」と1〜2文で案内する)`;
  uq += `\n\n【画面上部の「1000人シミュレーション」用・追加出力（必須）】本文の最後に、別行で \`@@RIVAL:<本文>@@\` を1回だけ出力する。<本文>は「${bizLabel ? bizLabel + "で、" : ""}あなたより“選ばれている”同業の店がGoogleビジネスプロフィール（GBP）で実際にやっていること」をMEO観点で1〜2文・専門用語なしで。写真の充実／クチコミへの返信／投稿の鮮度／カテゴリ・基本情報・メニューの整備など“お店が手を打てる要素”に限定し、営業時間帯・距離・立地などの外的要因や、クチコミの集め方・獲得テクニックには触れない。ユーザーの弱い項目に沿って具体的に。この印は画面には表示されない。`;
  return uq;
}
